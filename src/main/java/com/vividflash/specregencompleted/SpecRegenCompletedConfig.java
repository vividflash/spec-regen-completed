package com.vividflash.specregencompleted;

import net.runelite.client.config.Config;
import net.runelite.client.config.ConfigGroup;
import net.runelite.client.config.ConfigItem;
import net.runelite.client.config.Range;

@ConfigGroup(SpecRegenCompletedConfig.GROUP)
public interface SpecRegenCompletedConfig extends Config
{
    String GROUP = "specregencompleted";

    @ConfigItem(
        keyName = "sound",
        name = "Sound",
        description = "",
        position = 0
    )
    default SpecSound sound()
    {
        return SpecSound.ONE;
    }

    @ConfigItem(
        keyName = "volume",
        name = "Volume",
        description = "0 plays nothing.",
        position = 1
    )
    @Range(min = 0, max = 100)
    default int volume()
    {
        return 50;
    }
}
